#!/usr/bin/env python3
"""gen_opus_tables.py <libopus-dir> celt > src/codec/opusdec/celt/tables.rs

(SILK's tables come from tools/gen_silk_tables.c, which compiles
libopus's own SILK table sources and prints them.)

Writes the constant tables the Opus decoder (RFC 6716) needs, taken from
libopus — the RFC's own reference implementation, BSD-3-Clause, the
version vendored by the audiopus_sys 0.2.2 crate (`cargo fetch` it and
pass .../audiopus_sys-0.2.2/opus). Each source file is run through the C
preprocessor with libopus's float-build defines first, so the table
variants this generator reads are the ones a default libopus build
compiles (not the custom-modes or fixed-point alternatives).
"""
import re, subprocess, sys

O = sys.argv[1]
WHICH = sys.argv[2]

def pp(path, extra=()):
    return subprocess.run(
        ["gcc", "-E", "-P", "-DOPUS_BUILD", "-DUSE_ALLOCA", *extra,
         f"-I{O}/include", f"-I{O}/celt", f"-I{O}/silk", f"-I{O}/silk/float", f"-I{O}", f"{O}/{path}"],
        check=True, capture_output=True, text=True).stdout

_cache = {}
def src(path):
    if path not in _cache:
        _cache[path] = pp(path)
    return _cache[path]

def body(path, name):
    s = src(path)
    m = re.search(r"\b" + re.escape(name) + r"\s*(\[[^\]]*\])*\s*=\s*\{", s)
    if not m:
        raise SystemExit(f"{name} not found in {path}")
    i = m.end(); d = 1; j = i
    while d:
        d += {"{": 1, "}": -1}.get(s[j], 0); j += 1
    return s[i:j - 1]

def items(b):
    b = re.sub(r"\(\s*(opus_int16|opus_int32|opus_uint32|opus_val16|opus_val32|float|opus_int8|int|unsigned char|signed char)\s*\)", "", b)
    out = []
    for tok in re.split(r"[,{}]", b):
        tok = tok.strip()
        if not tok:
            continue
        tok = re.sub(r"(?<=[0-9.])[fFuUlL]+\b", "", tok)
        if re.fullmatch(r"-?[0-9]*\.?[0-9]+(e[-+]?[0-9]+)?", tok):
            # A plain literal is kept as written: C rounds it straight from
            # decimal to the table's type, which a trip through a Python
            # double could miss by an ulp.
            out.append(tok)
        else:
            out.append(repr(eval(tok, {}, {})))
    return out

out = ["//! Tables from libopus (RFC 6716's reference implementation, BSD-3-Clause),",
       "//! generated by `tools/gen_opus_tables.py` — see tools/THIRD_PARTY.md.",
       "//! Do not edit by hand.", "",
       "#![allow(clippy::unreadable_literal, clippy::excessive_precision, clippy::approx_constant)]", ""]

def emit(rust, ty, vals, per=12):
    out.append(f"pub(crate) const {rust}: [{ty}; {len(vals)}] = [")
    for k in range(0, len(vals), per):
        chunk = vals[k:k + per]
        if ty in ("f32", "f64"):
            out.append("    " + " ".join((v if any(c in v for c in ".e") else v + ".0") + "," for v in chunk))
        else:
            out.append("    " + " ".join(f"{int(float(v))}," for v in chunk))
    out.append("];\n")

def table(path, cname, rust, ty, n=None):
    v = items(body(path, cname))
    if n is not None:
        assert len(v) == n, (cname, len(v), n)
    emit(rust, ty, v)

if WHICH == "celt":
    M = "celt/modes.c"
    table(M, "eband5ms", "EBANDS", "i16", 22)
    table(M, "band_allocation", "BAND_ALLOCATION", "u8", 11 * 21)
    table(M, "window120", "WINDOW", "f32", 120)
    table(M, "logN400", "LOGN", "i16", 21)
    table(M, "cache_index50", "CACHE_INDEX", "i16", 105)
    table(M, "cache_bits50", "CACHE_BITS", "u8", 392)
    table(M, "cache_caps50", "CACHE_CAPS", "u8", 168)
    table(M, "fft_twiddles48000_960", "FFT_TWIDDLES", "f32", 960)
    for n in (480, 240, 120, 60):
        table(M, f"fft_bitrev{n}", f"FFT_BITREV{n}", "i16", n)
    table(M, "mdct_twiddles960", "MDCT_TWIDDLES", "f32")
    Q = "celt/quant_bands.c"
    table(Q, "eMeans", "E_MEANS", "f32", 25)
    table(Q, "pred_coef", "PRED_COEF", "f32", 4)
    table(Q, "beta_coef", "BETA_COEF", "f32", 4)
    table(Q, "e_prob_model", "E_PROB_MODEL", "u8", 4 * 2 * 42)
    table("celt/cwrs.c", "CELT_PVQ_U_DATA", "PVQ_U_DATA", "u32", 1272)
    table("celt/bands.c", "ordery_table", "ORDERY", "i16")
    table("celt/rate.c", "LOG2_FRAC_TABLE", "LOG2_FRAC", "u8", 24)
else:
    raise SystemExit("silk tables: use tools/gen_silk_tables.c")

sys.stdout.write("\n".join(out))
